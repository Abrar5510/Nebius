"""A synthetic capture that exercises every data contract without a phone or a GPU."""

from __future__ import annotations

from typing import Any

from .contracts import CAPTURE_SCHEMA
from .storage import Storage
from .util import iso_now, new_id


def seed_demo_capture(storage: Storage, *, capture_id: str | None = None) -> dict[str, Any]:
    capture_id = capture_id or new_id("cap")
    existing = f"captures/{capture_id}/capture.json"
    if storage.exists(existing):
        return storage.get_json(existing)

    narration = (
        "I am picking up the red mug by its handle, lifting it over the wooden coaster, "
        "and setting it down gently so it stays upright. Then I let go."
    )
    capture = {
        "schema_version": CAPTURE_SCHEMA,
        "capture_id": capture_id,
        "task_name": "Place the red mug on the wooden coaster",
        "skill": "place_cup",
        "narration": narration,
        "created_at": iso_now(),
        "duration_s": 12.0,
        "synthetic": True,
        "room": {
            "name": "Kitchen table",
            "bounds_m": [4.2, 2.6, 3.0],
            "table": {
                "center_m": [0.0, 0.0, 0.0],
                "size_m": [0.9, 0.04, 0.7],
                "material": "wood",
            },
            "lighting": "warm afternoon",
        },
        "objects": [
            {
                "id": "mug",
                "name": "red mug",
                "role": "target",
                "material": "ceramic",
                "mass_kg": 0.32,
                "friction": 0.55,
                "dimensions_m": [0.08, 0.08, 0.10],
                "position_m": [-0.18, -0.04, 0.045],
            },
            {
                "id": "coaster",
                "name": "wooden coaster",
                "role": "surface",
                "material": "wood",
                "mass_kg": 0.06,
                "friction": 0.60,
                "dimensions_m": [0.10, 0.10, 0.008],
                "position_m": [0.16, 0.22, 0.012],
            },
            {
                "id": "table",
                "name": "table",
                "role": "support",
                "material": "wood",
                "mass_kg": 12.0,
                "friction": 0.50,
                "dimensions_m": [0.90, 0.04, 0.70],
                "position_m": [0.0, 0.0, 0.0],
            },
            {
                "id": "plant",
                "name": "small plant",
                "role": "distractor",
                "material": "plastic",
                "mass_kg": 0.45,
                "friction": 0.45,
                "dimensions_m": [0.12, 0.12, 0.16],
                "position_m": [0.34, -0.10, 0.08],
            },
        ],
        "files": {
            "poses": f"captures/{capture_id}/poses.json",
            "narration": f"captures/{capture_id}/narration.txt",
            "room_scan": f"captures/{capture_id}/room_scan.json",
        },
    }
    poses = {
        "schema_version": "showitonce.arkit_poses/v1",
        "capture_id": capture_id,
        "camera": "iPhone LiDAR",
        "frames": [
            {
                "t": round(index * 0.5, 1),
                "position_m": [round(0.02 * index, 3), 1.2, 0.9],
                "rotation_quat": [1.0, 0.0, 0.0, 0.0],
            }
            for index in range(12)
        ],
    }
    room_scan = {
        "schema_version": "showitonce.room_scan/v1",
        "capture_id": capture_id,
        "mesh": "phone LiDAR sweep, 10 seconds",
        "bounds_m": capture["room"]["bounds_m"],
        "planes": [
            {"type": "table", "center_m": [0.0, 0.0, 0.0], "size_m": [0.9, 0.04, 0.7]}
        ],
    }
    storage.put_json(existing, capture)
    storage.put_text(f"captures/{capture_id}/narration.txt", narration)
    storage.put_json(f"captures/{capture_id}/poses.json", poses)
    storage.put_json(f"captures/{capture_id}/room_scan.json", room_scan)
    storage.put_text(
        f"captures/{capture_id}/README.txt",
        "Synthetic demo capture generated by `showitonce demo`.\n"
        "It carries the same schema as a phone capture and does not contain video or faces.\n",
    )
    return capture
